SELECT COUNT(*) total
FROM issue_return
WHERE status='Returned'
")->fetch_assoc()['total'];

$totalOverdue = $conn->query("
SELECT COUNT(*) total
FROM issue_return
WHERE status='Issued'
AND due_date < CURDATE()
")->fetch_assoc()['total'];

$totalFine = $conn->query("
SELECT IFNULL(SUM(fine),0) total
FROM issue_return
