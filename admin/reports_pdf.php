// ==========================
// Report Filters
// ==========================
$from    = $_GET['from'] ?? '';
$to      = $_GET['to'] ?? '';
$student = $_GET['student'] ?? '';
$status  = $_GET['status'] ?? '';

$sql = "
SELECT
    ir.transaction_id,
    s.full_name,
    b.title,
    ir.issue_date,
    ir.due_date,
    ir.return_date,
    ir.status,
    ir.fine
FROM issue_return ir
INNER JOIN student s
    ON ir.student_id = s.student_id
INNER JOIN book b
    ON ir.book_id = b.book_id
WHERE 1
";

$params = [];
$types = "";

// From Date
if (!empty($from)) {
    $sql .= " AND ir.issue_date >= ?";
    $params[] = $from;
    $types .= "s";
}

// To Date
if (!empty($to)) {
    $sql .= " AND ir.issue_date <= ?";
    $params[] = $to;
    $types .= "s";
}

// Student
if (!empty($student)) {
    $sql .= " AND ir.student_id = ?";
    $params[] = $student;
    $types .= "i";
}

$sql .= " ORDER BY ir.issue_date DESC";
$stmt = $conn->prepare($sql);

if (!empty($params)) {
    $stmt->bind_param($types, ...$params);
}

$stmt->execute();
$reportResult = $stmt->get_result(); 

// Summary Statistics
// ==========================

$totalTransaction = $reportResult->num_rows;

